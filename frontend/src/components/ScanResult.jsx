import { useCallback } from "react";
import { jsPDF } from "jspdf";

function ScanResult({ scanResult }) {

  const getStatusClass = useCallback((status) => {
    switch (status) {
      case "Safe":
        return "status-safe";

      case "Suspicious":
        return "status-suspicious";

      case "Malicious":
        return "status-malicious";

      default:
        return "";
    }
  }, []);


  const getStatusIcon = useCallback((status) => {
    switch (status) {

      case "Safe":
        return "🟢 Safe";

      case "Suspicious":
        return "🟡 Suspicious";

      case "Malicious":
        return "🔴 Malicious";

      default:
        return status;

    }
  }, []);



  const downloadReport = useCallback(() => {

    const report = `
==============================
        SECURESCAN REPORT
==============================

Website:
${scanResult.url}

Status:
${scanResult.status}

Security Score:
${scanResult.score}/100

HTTP Status:
${scanResult.statusCode}

Response Time:
${scanResult.responseTime}

HTTPS:
${scanResult.https ? "Enabled" : "Disabled"}

Server:
${scanResult.server}


Security Headers
------------------------------

Content Security Policy:
${scanResult.securityHeaders?.contentSecurityPolicy}

Strict Transport Security:
${scanResult.securityHeaders?.strictTransportSecurity}

X-Frame-Options:
${scanResult.securityHeaders?.xFrameOptions}

X-Content-Type-Options:
${scanResult.securityHeaders?.xContentTypeOptions}


Detected Vulnerabilities
------------------------------

${
  scanResult.vulnerabilities?.length
    ? scanResult.vulnerabilities.join("\n")
    : "No vulnerabilities detected."
}


Recommendations
------------------------------

${
  scanResult.recommendations?.length
    ? scanResult.recommendations.join("\n")
    : "No recommendations available."
}


Generated by SecureScan
==============================
`;



    const blob = new Blob(
      [report],
      {
        type:"text/plain"
      }
    );


    const url = URL.createObjectURL(blob);

    const link = document.createElement("a");

    link.href=url;
    link.download="SecureScan_Report.txt";

    link.click();

    URL.revokeObjectURL(url);


  }, [scanResult]);




  const downloadPDFReport = useCallback(() => {

    const doc = new jsPDF();

    let y = 20;


    doc.setFontSize(18);

    doc.text(
      "SecureScan Security Report",
      20,
      y
    );


    y += 15;


    doc.setFontSize(12);


    const details = [

      `Website: ${scanResult.url}`,

      `Status: ${scanResult.status}`,

      `Security Score: ${scanResult.score}/100`,

      `HTTP Status: ${scanResult.statusCode}`,

      `Response Time: ${scanResult.responseTime}`,

      `HTTPS: ${
        scanResult.https
        ? "Enabled"
        : "Disabled"
      }`,

      `Server: ${scanResult.server}`

    ];


    details.forEach((item)=>{

      doc.text(item,20,y);

      y+=10;

    });



    y+=10;


    doc.text(
      "Detected Vulnerabilities",
      20,
      y
    );


    y+=10;


    scanResult.vulnerabilities?.forEach(
      (item)=>{

        doc.text(
          `• ${item}`,
          20,
          y
        );

        y+=8;

      }
    );



    y+=10;


    doc.text(
      "Recommendations",
      20,
      y
    );


    y+=10;


    scanResult.recommendations?.forEach(
      (item)=>{

        doc.text(
          `• ${item}`,
          20,
          y
        );

        y+=8;

      }
    );



    doc.save(
      "SecureScan_Report.pdf"
    );


  },[scanResult]);



  if(!scanResult){

    return(

      <div className="card">

        <h2>
          Latest Scan Result
        </h2>

        <p>
          No scan performed yet.
        </p>

      </div>

    );

  }



  return (

    <div className="card">


      <h2>
        🔒 Latest Security Report
      </h2>



      <p>
        <strong>
          Website:
        </strong>

        {scanResult.url}

      </p>



      <p>

        <strong>
          Status:
        </strong>


        <span
        className={`status-badge ${
          getStatusClass(scanResult.status)
        }`}
        >

          {
            getStatusIcon(
              scanResult.status
            )
          }

        </span>

      </p>



      <p>
        <strong>
          Security Score:
        </strong>

        {scanResult.score}/100

      </p>



      <progress
        className="security-progress"
        value={scanResult.score}
        max="100"
      />



      <p>
        <strong>
          HTTP Status:
        </strong>

        {scanResult.statusCode}

      </p>



      <p>
        <strong>
          Response Time:
        </strong>

        {scanResult.responseTime}

      </p>



      <p>
        <strong>
          HTTPS:
        </strong>

        {
          scanResult.https
          ?"✅ Enabled"
          :"❌ Disabled"
        }

      </p>



      <p>
        <strong>
          Server:
        </strong>

        {scanResult.server}

      </p>




      <hr/>


      <h3>
        🛡 Security Headers
      </h3>


      {
        scanResult.securityHeaders
        ?

        <ul>

          {
          Object.entries(
            scanResult.securityHeaders
          )
          .map(
            ([key,value])=>(

              <li key={key}>
                {key}: {value}
              </li>

            )
          )
          }

        </ul>

        :

        <p>
          No security header information available.
        </p>

      }



      <hr/>


      <h3>
        ⚠ Detected Vulnerabilities
      </h3>


      {

      scanResult.vulnerabilities?.length

      ?

      <ul>

      {
      scanResult.vulnerabilities.map(
        (item,index)=>(

          <li key={`${item}-${index}`}>
            {item}
          </li>

        )
      )
      }

      </ul>

      :

      <p>
        ✅ No vulnerabilities detected.
      </p>

      }



      <hr/>


      <h3>
        💡 Recommendations
      </h3>


      {

      scanResult.recommendations?.length

      ?

      <ul>

      {
      scanResult.recommendations.map(
        (item,index)=>(

          <li key={`${item}-${index}`}>
            {item}
          </li>

        )
      )
      }

      </ul>


      :

      <p>
        No recommendations available.
      </p>

      }



      <div className="report-buttons">


        <button
        className="txt-report-btn"
        onClick={downloadReport}
        >

          📄 Download TXT Report

        </button>



        <button
        className="pdf-report-btn"
        onClick={downloadPDFReport}
        >

          📑 Download PDF Report

        </button>


      </div>


    </div>

  );

}


export default ScanResult;